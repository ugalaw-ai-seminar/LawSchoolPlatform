#!/usr/bin/env node
// LOQUITUR MCP server: exposes the RES legal study tools to coding agents
// (Claude Code, Cursor, Codex CLI, Gemini CLI, VS Code, etc.) over stdio.
//
// Two operating modes:
//   Provider mode  LOQUITUR_PROVIDER + LOQUITUR_API_KEY are set. The server calls
//                  Gemini, Claude, or OpenAI itself with difficulty-based model routing.
//   Host mode      No key set. AI tools return RES's exact instructions and the host
//                  agent (which is already an LLM) carries them out. No second key needed.

import fs from 'node:fs';
import path from 'node:path';
import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { z } from 'zod';
import mammoth from 'mammoth';

import { providerConfig, runAI, getDifficulty, modelFor, modelForTask } from './providers.js';
import * as store from './store.js';
import { startSync, SYNC_PORT } from './sync.js';
import * as P from './prompts.js';

const server = new McpServer({ name: 'loquitur', version: '1.0.0' });

// ── helpers ──────────────────────────────────────────────

const ok = text => ({ content: [{ type: 'text', text }] });
const fail = text => ({ content: [{ type: 'text', text }], isError: true });

async function readInput({ text, file_path }) {
  if (text && text.trim()) return text;
  if (!file_path) throw new Error('Provide either text or file_path.');
  const p = path.resolve(file_path);
  if (!fs.existsSync(p)) throw new Error(`File not found: ${p}`);
  if (p.toLowerCase().endsWith('.docx')) return (await mammoth.extractRawText({ path: p })).value;
  if (p.toLowerCase().endsWith('.pdf')) throw new Error('PDF input is not supported yet. Export the PDF to .txt or .docx first.');
  return fs.readFileSync(p, 'utf8');
}

function writeOutput(output_path, content) {
  const p = path.resolve(output_path);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
  return p;
}

function requireCourse(state, ref) {
  const c = store.findCourse(state, ref);
  if (!c) {
    const names = state.courses.map(x => x.name).join(', ') || 'none yet';
    throw new Error(`Course "${ref}" not found. Existing courses: ${names}. Use add_course first.`);
  }
  return c;
}

/**
 * Run a RES prompt through the configured provider, or hand it to the host agent.
 * onResult(text) post-processes provider output; hostNote explains follow-up steps in host mode.
 */
async function runOrDelegate(spec, { onResult, hostNote = '', outputPath } = {}) {
  const cfg = providerConfig();
  if (!cfg) {
    const save = outputPath ? `\n\nWhen finished, write the result to: ${path.resolve(outputPath)}` : '';
    return ok(
      `HOST MODE: no LOQUITUR_API_KEY is configured, so carry out this RES task yourself and show the result to the user.\n` +
        `Suggested effort: ${getDifficulty(spec.task)}.${save}${hostNote ? `\n\n${hostNote}` : ''}\n\n` +
        `<res_system>\n${spec.system}\n</res_system>\n\n<res_task>\n${spec.prompt}\n</res_task>`
    );
  }
  const { text, model } = await runAI(cfg, spec.system, spec.prompt, spec.task);
  const body = onResult ? await onResult(text) : text;
  let tail = `\n\n_Generated by RES via ${cfg.provider}/${model}._`;
  if (outputPath) tail += `\n_Saved to ${writeOutput(outputPath, typeof body === 'string' ? body : text)}_`;
  return ok((typeof body === 'string' ? body : text) + tail);
}

function tool(name, description, inputSchema, handler) {
  server.registerTool(name, { description, inputSchema }, async args => {
    try {
      return await handler(args);
    } catch (e) {
      return fail(`Error: ${e.message}`);
    }
  });
}

const DAYS = z.enum(['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']);

// Each outline type is saved separately so building one never overwrites another.
// outlineData is the web app's field for comprehensive outlines; attackOutlineData matches the web app too.
const OUTLINE_FIELDS = { full: 'outlineData', attack: 'attackOutlineData', checklist: 'checklistOutlineData' };

// ── status ───────────────────────────────────────────────

tool('loquitur_status', 'Show LOQUITUR configuration: provider mode or host mode, model routing, and where data is stored.', {}, async () => {
  const cfg = providerConfig();
  const s = store.load();
  const mode = cfg
    ? `Provider mode: ${cfg.provider}\n  easy → ${modelFor(cfg.provider, 'easy')}\n  normal → ${modelFor(cfg.provider, 'normal')}\n  hard → ${modelFor(cfg.provider, 'hard')}\n  outlines → ${modelForTask(cfg.provider, 'outline_full')}`
    : 'Host mode: no API key configured; the calling agent runs RES prompts itself.';
  return ok(`${mode}\nData file: ${store.statePath}\nBrowser app sync: http://127.0.0.1:${SYNC_PORT} (the app shares this file while this server runs)\nCourses: ${s.courses.length} · Quiz results: ${s.quizResults.length} · Billable entries: ${s.billableLog.length}`);
});

// ── courses & schedule ───────────────────────────────────

tool(
  'add_course',
  'Add a law school course, optionally with classroom, meeting time, and meeting days. These feed the weekly schedule and study plans.',
  {
    name: z.string().describe('Course name, e.g. "Civil Procedure"'),
    professor: z.string().optional(),
    room: z.string().optional().describe('Classroom, e.g. "Room 214"'),
    time: z.string().optional().describe('Meeting time, e.g. "9:00-10:15 AM"'),
    days: z.array(DAYS).optional().describe('Meeting days'),
  },
  async ({ name, professor, room, time, days }) => {
    const s = store.load();
    if (store.findCourse(s, name)?.name.toLowerCase() === name.toLowerCase()) throw new Error(`"${name}" already exists.`);
    // Same shape as addCourse() in the web app (it reads prof, not professor)
    const course = { id: store.newId(), name, prof: professor || '', credits: 3, room: room || '', time: time || '', days: days || [], materials: [], notes: [], assignments: [], deadlines: [], outlineData: null, progress: 0 };
    s.courses.push(course);
    store.save(s);
    return ok(`Added ${name} (id ${course.id})${days?.length ? ` meeting ${days.join('/')} ${time || ''}${room ? ` in ${room}` : ''}` : ''}.`);
  }
);

tool('list_courses', 'List saved courses with schedule details, material counts, and whether an outline exists.', {}, async () => {
  const s = store.load();
  if (!s.courses.length) return ok('No courses yet. Use add_course.');
  return ok(
    s.courses
      .map(c => {
        const saved = Object.entries(OUTLINE_FIELDS).filter(([, f]) => c[f]).map(([t]) => t);
        return `- ${c.name} [${c.id}]${c.days?.length ? ` · ${c.days.join('/')} ${c.time}` : ''}${c.room ? ` · ${c.room}` : ''} · ${c.materials.length} materials, ${c.notes.length} notes, ${c.assignments.length} assignments${saved.length ? ` · outlines saved: ${saved.join(', ')}` : ''}`;
      })
      .join('\n')
  );
});

tool(
  'add_course_material',
  'Attach course material (syllabus, reading, notes file, transcript of lecture) to a course so RES can use it as context. Accepts raw text or a .txt/.md/.docx file path.',
  {
    course: z.string().describe('Course name or id'),
    name: z.string().optional().describe('Label for the material'),
    text: z.string().optional(),
    file_path: z.string().optional(),
  },
  async ({ course, name, text, file_path }) => {
    const s = store.load();
    const c = requireCourse(s, course);
    const content = await readInput({ text, file_path });
    c.materials.push({ id: store.newId(), name: name || (file_path ? path.basename(file_path) : 'Pasted material'), content, addedAt: new Date().toISOString() });
    store.save(s);
    return ok(`Added ${content.length.toLocaleString()} characters to ${c.name}.`);
  }
);

tool(
  'add_assignment',
  'Add a dated assignment or exam to a course. Used by study_plan.',
  { course: z.string(), name: z.string(), date: z.string().describe('YYYY-MM-DD') },
  async ({ course, name, date }) => {
    const s = store.load();
    const c = requireCourse(s, course);
    c.assignments.push({ id: store.newId(), name, date, time: '', completed: false });
    store.save(s);
    return ok(`Added "${name}" due ${date} to ${c.name}.`);
  }
);

tool('weekly_schedule', 'Show the weekly class schedule built from course meeting days, times, and rooms.', {}, async () => {
  const s = store.load();
  const order = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  const lines = order
    .map(d => {
      const cs = s.courses.filter(c => c.days?.includes(d));
      return cs.length ? `${d}: ${cs.map(c => `${c.name}${c.time ? ` ${c.time}` : ''}${c.room ? ` (${c.room})` : ''}`).join('; ')}` : null;
    })
    .filter(Boolean);
  return ok(lines.length ? lines.join('\n') : 'No scheduled classes. Add days and times with add_course.');
});

// ── outlines & study tools ───────────────────────────────

tool(
  'build_outline',
  'Build a law school course outline (full, attack, or issue-spotter checklist) from the student\'s notes and saved course materials. Optionally write it to a markdown file.',
  {
    course: z.string().describe('Course name or id'),
    type: z.enum(['full', 'attack', 'checklist']).default('full'),
    notes: z.string().optional().describe('Notes text to use as the primary source'),
    notes_file: z.string().optional().describe('Path to a .txt/.md/.docx notes file'),
    output_path: z.string().optional().describe('Where to save the outline, e.g. ./outlines/civpro.md'),
  },
  async ({ course, type, notes, notes_file, output_path }) => {
    const s = store.load();
    const c = requireCourse(s, course);
    const userNotes = notes || notes_file ? await readInput({ text: notes, file_path: notes_file }) : '';
    const spec = P.outline({ courseName: c.name, type, notes: userNotes, materials: store.gatherCourseContext(c) });
    return runOrDelegate(spec, {
      outputPath: output_path,
      onResult: text => {
        const fresh = store.load();
        const fc = store.findCourse(fresh, c.id);
        fc[OUTLINE_FIELDS[type] || OUTLINE_FIELDS.full] = text;
        store.save(fresh);
        return text;
      },
    });
  }
);

tool(
  'study_tool',
  'Run a RES study tool for a course: practice questions with answers, a Socratic cold-call simulation, or a full exam hypothetical with model answer.',
  { course: z.string(), kind: z.enum(['practice-questions', 'cold-call', 'exam-hypo']) },
  async ({ course, kind }) => {
    const s = store.load();
    const c = requireCourse(s, course);
    return runOrDelegate(P.studyTool({ kind, courseName: c.name, materials: store.gatherCourseContext(c) }));
  }
);

tool(
  'study_plan',
  'Generate a time-blocked weekly study plan from saved courses, class times, and upcoming assignments.',
  {},
  async () => {
    const s = store.load();
    if (!s.courses.length) throw new Error('Add courses first.');
    const courses = s.courses.map(c => ({
      name: c.name,
      meets: c.days?.length ? `${c.days.join('/')} ${c.time}` : undefined,
      upcoming: c.assignments.filter(a => !a.completed).map(a => ({ name: a.name, date: a.date })),
    }));
    return runOrDelegate(P.studyPlan(courses));
  }
);

// ── quizzing & weak areas ────────────────────────────────

tool(
  'generate_quiz',
  'Generate a quiz for a course (MBE multiple choice, short answer, issue spotter, or exam hypo). Returns a quiz_id; present the questions, collect the student\'s answers, then call grade_quiz. Can target the student\'s recorded weak areas.',
  {
    course: z.string(),
    type: z.enum(['mbe', 'short', 'issue-spot', 'hypo']).default('mbe'),
    difficulty: z.enum(['early', 'mid', 'final']).default('mid'),
    topic: z.string().optional(),
    focus_weak_areas: z.boolean().default(false).describe('Bias questions toward topics the student has scored poorly on'),
  },
  async ({ course, type, difficulty, topic, focus_weak_areas }) => {
    const s = store.load();
    const c = requireCourse(s, course);
    const weak = focus_weak_areas ? store.weakAreas(s).filter(w => w.course === c.name) : [];
    const spec = P.quiz({ courseName: c.name, qtype: type, difficulty, topic, materials: store.gatherCourseContext(c), weak });
    const topicLabel = topic || (weak.length ? weak[0].topic : c.name);

    if (!providerConfig()) {
      return runOrDelegate(spec, {
        hostNote:
          `After generating, show the questions without answers and wait for the student's responses. ` +
          `Grade them as a law professor would (for written answers use a 10-point rubric per question). ` +
          `Then call record_quiz_score with course="${c.name}", topic="${topicLabel}", question_type="${type}", and the percentage score so weak areas are tracked.`,
      });
    }

    const cfg = providerConfig();
    const { text, model } = await runAI(cfg, spec.system, spec.prompt, spec.task);
    const questions = type === 'mbe' ? P.parseMBE(text) : P.parseText(text);
    if (!questions.length) return ok(`${text}\n\n(Could not parse structured questions; grade manually and use record_quiz_score.)`);
    const id = store.newId();
    const fresh = store.load();
    fresh.quizzes[id] = { id, course: c.name, topic: topicLabel, type, questions, createdAt: new Date().toISOString() };
    store.save(fresh);
    const rendered = questions
      .map((q, i) => `### Question ${i + 1}\n${q.question}${q.options ? '\n' + Object.entries(q.options).map(([k, v]) => `${k}. ${v}`).join('\n') : ''}`)
      .join('\n\n');
    return ok(`quiz_id: ${id}\n\n${rendered}\n\n_Generated via ${cfg.provider}/${model}. Collect the student's answers, then call grade_quiz with quiz_id and an answers array${type === 'mbe' ? ' of letters (A-D)' : ''}._`);
  }
);

tool(
  'grade_quiz',
  'Grade a quiz created by generate_quiz and record the score toward weak-area tracking.',
  {
    quiz_id: z.string(),
    answers: z.array(z.string()).describe('One answer per question, in order. For MBE use letters A-D.'),
  },
  async ({ quiz_id, answers }) => {
    const s = store.load();
    const q = s.quizzes[quiz_id];
    if (!q) throw new Error(`Unknown quiz_id ${quiz_id}.`);
    if (answers.length !== q.questions.length) throw new Error(`Expected ${q.questions.length} answers, got ${answers.length}.`);
    const norm = q.type === 'mbe' ? answers.map(a => a.trim().toUpperCase().charAt(0)) : answers;
    const spec = q.type === 'mbe' ? P.gradeMBE(q.questions, norm) : P.gradeText(q.questions, norm);
    return runOrDelegate(spec, {
      onResult: text => {
        const score = P.extractScore(text, q.type, q.questions.length);
        const fresh = store.load();
        if (score !== null) fresh.quizResults.push({ course: q.course, topic: q.topic, questionType: q.type, score, date: new Date().toISOString() });
        delete fresh.quizzes[quiz_id];
        store.save(fresh);
        return `${text}\n\n${score !== null ? `**Recorded score: ${score}%** for ${q.course} / ${q.topic}.` : '_Could not detect a score; use record_quiz_score to log it._'}`;
      },
    });
  }
);

tool(
  'record_quiz_score',
  'Record a quiz or practice score (0-100) for a course topic so weak areas are tracked over time.',
  {
    course: z.string(),
    topic: z.string(),
    score: z.number().min(0).max(100),
    question_type: z.string().optional(),
  },
  async ({ course, topic, score, question_type }) => {
    const s = store.load();
    const name = store.findCourse(s, course)?.name || course;
    s.quizResults.push({ course: name, topic, questionType: question_type || '', score: Math.round(score), date: new Date().toISOString() });
    store.save(s);
    return ok(`Recorded ${Math.round(score)}% for ${name} / ${topic}.`);
  }
);

tool('weak_areas', 'List the student\'s weakest topics (average under 65%) based on recorded quiz scores, worst first.', {}, async () => {
  const w = store.weakAreas(store.load());
  if (!w.length) return ok('No weak areas recorded. Every tracked topic averages 65% or higher, or no quizzes have been scored yet.');
  return ok(w.map(x => `- ${x.course} / ${x.topic}: ${x.avg}% avg over ${x.attempts} attempt${x.attempts > 1 ? 's' : ''}`).join('\n'));
});

// ── Bluebook ─────────────────────────────────────────────

tool(
  'bluebook',
  'Bluebook (21st ed.) citation help. mode=generate builds a citation from source details; mode=fix corrects an existing citation and explains changes; mode=draft writes a legal paragraph with citations to real authorities (verify every authority before relying on it).',
  {
    mode: z.enum(['generate', 'fix', 'draft']),
    source_type: z.string().optional().describe('generate: case, statute, regulation, book, law review article, website...'),
    details: z.string().optional().describe('generate: parties, reporter, volume, page, court, year, etc.'),
    format: z.enum(['full', 'short', 'id']).optional().describe('generate: citation form'),
    citation: z.string().optional().describe('fix: the citation to correct'),
    topic: z.string().optional().describe('draft: the legal point to write about'),
    jurisdiction: z.string().optional().describe('draft: e.g. "Georgia"'),
  },
  async a => {
    if (a.mode === 'generate' && !a.details) throw new Error('generate needs details.');
    if (a.mode === 'fix' && !a.citation) throw new Error('fix needs citation.');
    if (a.mode === 'draft' && !a.topic) throw new Error('draft needs topic.');
    return runOrDelegate(P.bluebook({ mode: a.mode, sourceType: a.source_type, details: a.details, format: a.format, citation: a.citation, topic: a.topic, jurisdiction: a.jurisdiction }));
  }
);

// ── notes ────────────────────────────────────────────────

tool(
  'reorganize_notes',
  'Restructure messy class notes into clean markdown with headings and bullets, preserving every substantive point. Accepts text or a .txt/.md/.docx file; can save to output_path. Optionally saves the result as a note on a course.',
  { text: z.string().optional(), file_path: z.string().optional(), output_path: z.string().optional(), course: z.string().optional() },
  async ({ text, file_path, output_path, course }) => {
    const input = await readInput({ text, file_path });
    return runOrDelegate(P.reorganizeNotes(input), {
      outputPath: output_path,
      onResult: out => {
        if (course) {
          const s = store.load();
          const c = requireCourse(s, course);
          c.notes.push({ id: store.newId(), text: out, createdAt: new Date().toISOString() });
          store.save(s);
        }
        return out;
      },
    });
  }
);

tool(
  'generate_diagram',
  'Turn notes into one or more Mermaid flowcharts (graph TD) showing doctrine hierarchy, elements, and exceptions. Returns markdown with ```mermaid blocks; output_path saves a .md file that renders on GitHub, VS Code, and Obsidian.',
  { text: z.string().optional(), file_path: z.string().optional(), output_path: z.string().optional() },
  async ({ text, file_path, output_path }) => {
    const input = await readInput({ text, file_path });
    return runOrDelegate(P.diagram(input), {
      outputPath: output_path,
      hostNote: 'Wrap each diagram in a ```mermaid code block under its ## title when presenting or saving it.',
      onResult: raw => {
        const sections = P.parseDiagrams(raw);
        return sections.map(sct => `## ${sct.title}\n\n\`\`\`mermaid\n${sct.code}\n\`\`\``).join('\n\n');
      },
    });
  }
);

// ── billable hours ───────────────────────────────────────

tool(
  'log_billable_time',
  'Log a billable or tracked time entry (activity, matter, duration). Durations are stored in minutes; reports show tenths of an hour.',
  {
    activity: z.string(),
    matter: z.string().optional().describe('Client, matter, clinic case, or course'),
    minutes: z.number().positive().optional(),
    hours: z.number().positive().optional(),
    date: z.string().optional().describe('YYYY-MM-DD, defaults to today'),
  },
  async ({ activity, matter, minutes, hours, date }) => {
    const mins = minutes ?? (hours ? hours * 60 : null);
    if (!mins) throw new Error('Provide minutes or hours.');
    const s = store.load();
    s.billableLog.push({ id: store.newId(), activity, matter: matter || '', minutes: Math.round(mins), date: date || new Date().toISOString().slice(0, 10), source: 'agent' });
    store.save(s);
    return ok(`Logged ${(Math.ceil(mins / 6) / 10).toFixed(1)} hr: ${activity}${matter ? ` (${matter})` : ''}.`);
  }
);

tool(
  'billable_report',
  'Summarize logged time by matter, or export all entries as CSV (optionally to output_path).',
  { format: z.enum(['summary', 'csv']).default('summary'), matter: z.string().optional(), output_path: z.string().optional() },
  async ({ format, matter, output_path }) => {
    const s = store.load();
    let log = s.billableLog;
    if (matter) log = log.filter(e => e.matter.toLowerCase().includes(matter.toLowerCase()));
    if (!log.length) return ok('No time entries logged.');
    const tenths = m => (Math.ceil(m / 6) / 10).toFixed(1);
    if (format === 'csv') {
      const esc = v => `"${String(v).replace(/"/g, '""')}"`;
      const csv = 'Date,Activity,Matter,Minutes,Hours\n' + log.map(e => [e.date, e.activity, e.matter, e.minutes, tenths(e.minutes)].map(esc).join(',')).join('\n') + '\n';
      return ok(output_path ? `Wrote ${log.length} entries to ${writeOutput(output_path, csv)}` : csv);
    }
    const by = {};
    for (const e of log) by[e.matter || '(no matter)'] = (by[e.matter || '(no matter)'] || 0) + e.minutes;
    const total = log.reduce((a, e) => a + e.minutes, 0);
    return ok(Object.entries(by).map(([m, mins]) => `- ${m}: ${tenths(mins)} hr`).join('\n') + `\nTotal: ${tenths(total)} hr across ${log.length} entries`);
  }
);

// ── start ────────────────────────────────────────────────

const transport = new StdioServerTransport();
await server.connect(transport);
startSync();
console.error(`[loquitur] MCP server ready (${providerConfig() ? 'provider' : 'host'} mode). Data: ${store.statePath}`);
